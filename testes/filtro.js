const { chromium } = require('playwright');
const OUT = process.argv[2] || require('path').join(require('os').tmpdir(), 'dujoao-telas');
const B = 'http://localhost:8790';
const post = async (o) => (await fetch(B + '/exec', { method: 'POST', body: JSON.stringify(o) })).json();
(async () => {
  await fetch(B + '/__reset');
  for (const [i, n] of [[1, 'Ana Souza'], [2, 'Bia Lima'], [3, 'Caio Reis']]) await post({ acao: 'pedido', idEnvio: 'f' + i, nome: n, email: 'p' + i + '@example.com', itens: [{ id: 'torresmo-180', qtd: i, preco: 2800 }] });
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })).newPage();
  p.on('pageerror', (e) => console.log('PAGEERROR', e.message));
  await p.goto(B + '/painel.html', { waitUntil: 'networkidle' });
  await p.fill('#senha', '  senha-teste-123 '); await p.click('#entrar'); await p.waitForSelector('#app:not([hidden])');
  const chips = async () => (await p.$$eval('[data-filtro]', (els) => els.map((e) => e.textContent.replace(/\s+/g, ' ').trim()))).join(' | ');
  console.log('senha colada com espaços entrou:', await p.isVisible('#app'));
  console.log('antes :', await chips(), '| aba:', await p.textContent('#n-tickets'));
  await p.click('.ticket[data-numero="0003"] .alternar[data-campo="pago"]');
  await p.waitForTimeout(300);
  await p.click('.ticket[data-numero="0003"] .alternar[data-campo="entregue"]');
  await p.waitForTimeout(2500);
  console.log('toast :', await p.textContent('#toast'));
  console.log('depois:', await chips(), '| aba:', await p.textContent('#n-tickets'));
  console.log('em aberto mostra:', await p.$$eval('.ticket', (t) => t.map((x) => x.dataset.numero).join(',')));
  await p.click('[data-filtro="concluidos"]'); await p.waitForTimeout(200);
  console.log('concluídos mostra:', await p.$$eval('.ticket', (t) => t.map((x) => x.dataset.numero).join(',')));
  await p.click('[data-filtro="todos"]'); await p.waitForTimeout(200);
  console.log('todos mostra:', await p.$$eval('.ticket', (t) => t.map((x) => x.dataset.numero).join(',')));
  await p.click('[data-filtro="abertos"]');
  await p.screenshot({ path: OUT + '/f-abertos.png' });
  await b.close();
})();
